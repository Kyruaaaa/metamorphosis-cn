# Packs the .glb models that rocks.js uses into models/models.js, so the 3D models also
# load when index.html is opened straight from disk (browsers block loading
# .glb files from file:// pages). Run it again whenever a model changes:
#
#     python3 embed-models.py

import base64, json, pathlib, re

here = pathlib.Path(__file__).parent
# only the models rocks.js actually uses
used = set(re.findall(r'["\'](models/[^"\']+\.glb)["\']', (here / 'rocks.js').read_text()))
data = {}
for path in sorted(used):
    if (here / path).exists():
        data[path] = base64.b64encode((here / path).read_bytes()).decode()
    elif path != 'models/x.glb':          # the example in rocks.js' header
        print('missing:', path)
out = here / 'models' / 'models.js'
out.write_text('// generated by embed-models.py — do not edit\nwindow.MODEL_DATA = ' + json.dumps(data) + ';\n')
print(f'packed {len(data)} model(s) into {out.relative_to(here)}')
